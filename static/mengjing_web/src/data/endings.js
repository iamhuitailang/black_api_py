export const getEndingsByPatient = (patientId) => endings[patientId] || []
export const getEndingById = (patientId, endingId) => {
  return endings[patientId]?.find(e => e.id === endingId) || null
}

export const determineEnding = (patientId, trustLevel, fearLevel) => {
  const patientEndings = endings[patientId]
  if (!patientEndings) return null
  
  for (const ending of patientEndings) {
    if (trustLevel >= ending.requirement.trust && fearLevel <= ending.requirement.fear) {
      return ending
    }
  }
  
  return patientEndings[patientEndings.length - 1]
}
